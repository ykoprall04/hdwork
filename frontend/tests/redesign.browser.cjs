const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.HD_PREVIEW_URL || 'http://127.0.0.1:5193';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.HD_CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    page.setDefaultTimeout(10000);
    let role = 'SUPER_ADMIN', modules = ['TIAL', 'REQ', 'LOGIC_PSB', 'LOGIC_MO', 'B2B', 'ASSUREN', 'REPLACEMENT'];
    const requests = [], errors = [];
    let authenticated = true, allowLogout = false;
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => {
      sessionStorage.setItem('hdwork:operational:checkin:2', 'ONLINE');
      window.EventSource = class extends EventTarget { close() {} };
    });
    await page.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url());
      const headers = { 'access-control-allow-origin': req.headers().origin || base, 'access-control-allow-credentials': 'true', 'access-control-allow-headers': 'Content-Type,X-CSRF-Token' };
      if (req.method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
      requests.push({ method: req.method(), path: url.pathname, query: Object.fromEntries(url.searchParams) });
      if (req.method() === 'POST' && url.pathname.endsWith('/auth/logout') && allowLogout) { authenticated = false; return route.fulfill({ headers, json: { success: true } }); }
      assert.equal(req.method(), 'GET', 'Navigation and local preferences must not mutate server data');
      if (url.pathname.endsWith('/auth/me') && !authenticated) return route.fulfill({ status: 401, headers, json: { success: false } });
      let json;
      const counts = { total: 25, waiting: 10, process: 8, done: 5, failed: 2, averageDurationSeconds: 420 };
      if (url.pathname.endsWith('/auth/me')) json = { success: true, csrf: 'a'.repeat(64), data: { id: 2, name: 'Petugas Pengujian', username: 'synthetic', role, modules, city_id: null } };
      else if (url.pathname.endsWith('/overview')) json = { all: counts, TIAL: counts, LOGIC: counts };
      else if (url.pathname.endsWith('/recap')) json = { data: counts };
      else if (url.pathname.endsWith('/orders')) json = { data: [{ id: 'order-fixture', command: 'order', module: 'TIAL', status: 'WAITING', scIn: 'SC-SYNTHETIC', inetMasked: '••••0001', ownerName: null, receivedAt: '2026-11-11T01:00:00Z' }], page: 1, hasMore: false, serverNow: '2026-11-11T02:00:00Z' };
      else if (url.pathname.endsWith('/orders/order-fixture')) json = { data: { id: 'order-fixture', command: 'order', module: 'TIAL', status: 'WAITING', scIn: 'SC-SYNTHETIC', receivedAt: '2026-11-11T01:00:00Z' }, previous: null, history: [], page: 1, hasMore: false };
      else json = { data: [], page: 1, hasMore: false };
      await route.fulfill({ headers, json });
    });
    await page.goto(base + '/work/B2C/TIAL');
    await page.getByRole('link', { name: 'SC-SYNTHETIC', exact: true }).waitFor();
    await page.evaluate(() => document.fonts.ready);
    const nav = page.locator('.op-sidebar').getByRole('navigation', { name: 'Navigasi operasional' });
    assert.equal(await nav.getByRole('link', { name: 'TIAL / REQ', exact: true }).getAttribute('aria-current'), 'page');
    assert.ok(await page.locator('table').evaluate(el => el.getBoundingClientRect().top) < 650);
    await page.getByRole('button', { name: 'Ciutkan sidebar', exact: true }).click();
    assert.equal(await nav.getByRole('link', { name: 'B2C', exact: true }).getAttribute('aria-current'), 'page');
    await page.reload(); await page.getByRole('button', { name: 'Perlebar sidebar', exact: true }).click();
    await page.getByRole('button', { name: 'Menu akun', exact: true }).click();
    await page.getByLabel('Status kerja', { exact: true }).selectOption('SIBUK');
    await page.keyboard.press('Escape');
    await page.getByText('SIBUK · status lokal', { exact: true }).waitFor();
    await page.getByLabel('Pencarian pekerjaan', { exact: true }).fill('SC-TEST');
    await page.waitForFunction(() => !document.querySelector('main').innerText.includes('Memperbarui data…'));
    await page.waitForTimeout(450);
    assert.equal(requests.filter(r => r.path.endsWith('/orders')).at(-1).query.q, 'SC-TEST');
    await page.getByText('Filter lanjutan', { exact: true }).click();
    await page.getByLabel('Jenis perintah', { exact: true }).selectOption('req');
    await page.getByLabel('Tanggal mulai', { exact: true }).fill('2026-11-01');
    await page.getByLabel('Tanggal akhir', { exact: true }).fill('2026-11-11');
    await page.waitForTimeout(200);
    assert.equal(requests.filter(r => r.path.endsWith('/orders')).at(-1).query.command, 'req');
    assert.equal(requests.filter(r => r.path.endsWith('/orders')).at(-1).query.from, '2026-11-01');
    await page.getByRole('button', { name: 'Semua tanggal / reset filter', exact: true }).click();
    await page.waitForTimeout(450);
    assert.equal(requests.filter(r => r.path.endsWith('/orders')).at(-1).query.q, '');
    await page.getByText('Filter lanjutan', { exact: true }).click();
    await nav.getByRole('link', { name: 'LOGIC / SOLVER', exact: true }).click();
    await page.getByRole('heading', { name: 'Daftar pekerjaan LOGIC / SOLVER', exact: true }).waitFor();
    assert.equal(await nav.getByRole('link', { name: 'LOGIC / SOLVER', exact: true }).getAttribute('aria-current'), 'page');
    await page.goto(base + '/work/B2C');
    await page.getByRole('button', { name: 'Buka antrean TIAL', exact: true }).waitFor();
    assert.equal(await page.locator('.op-dashboard-metric').count(), 6);
    for (const width of [768, 390, 320]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(base + '/work/B2C/TIAL');
      await page.getByRole('link', { name: 'SC-SYNTHETIC', exact: true }).waitFor();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No body overflow at ${width}px`);
      if (width === 390) assert.ok(await page.getByRole('link', { name: 'SC-SYNTHETIC', exact: true }).evaluate(el => el.getBoundingClientRect().top) < 900);
      const trigger = page.getByRole('button', { name: 'Buka navigasi', exact: true });
      await trigger.click(); await page.getByRole('dialog').waitFor();
      await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'hidden' });
      assert.equal(await trigger.evaluate(el => el === document.activeElement), true, 'Escape restores focus');
      await trigger.click();
      await page.getByRole('dialog').getByRole('link', { name: 'TIAL / REQ', exact: true }).click();
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      await trigger.click();
      await page.getByRole('dialog').getByRole('link', { name: 'LOGIC / SOLVER', exact: true }).click();
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      await page.waitForURL('**/work/B2C/LOGIC');
    }
    await page.setViewportSize({ width: 1440, height: 900 });
    role = 'HD'; modules = ['TIAL'];
    await page.goto(base + '/jobs');
    await page.getByRole('heading', { name: 'Apa yang Anda kerjakan hari ini?', exact: true }).waitFor();
    assert.equal(await page.locator('main h2').count(), 1);
    assert.equal(await nav.getByRole('link', { name: 'LOGIC / SOLVER', exact: true }).count(), 0);
    assert.equal(await nav.getByRole('link', { name: 'Manajemen Pengguna', exact: true }).count(), 0);
    await page.goto(base + '/work/B2C/LOGIC');
    await page.getByRole('heading', { name: 'Akses LOGIC belum diberikan', exact: true }).waitFor();
    role = 'SHOW_ONLY';
    await page.goto(base + '/work/B2C/TIAL');
    await page.getByRole('link', { name: 'SC-SYNTHETIC', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'PICK', exact: true }).count(), 0);
    assert.equal(await nav.getByRole('link', { name: 'Telegram Live Chat', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Gunakan mode malam', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('dark')), true);
    assert.ok(requests.every(r => r.method === 'GET'));
    allowLogout = true;
    await page.getByRole('button', { name: 'Menu akun', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Logout', exact: true }).click();
    await page.waitForURL('**/login');
    assert.equal(await page.evaluate(() => sessionStorage.getItem('hdwork:operational:checkin:2')), null);
    assert.equal(requests.filter(r => r.method === 'POST').length, 1);
    assert.deepEqual(errors, []);
    console.log('PASS: sidebar, persisted collapse, active links, local profile status, filters, dashboard, 320/390/768/1440 geometry, drawer close/focus/navigation, module and role boundaries, dark theme, explicit logout/cleared check-in; no navigation mutations.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
